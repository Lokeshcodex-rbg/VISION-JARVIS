/**
 * VISION AI — Autonomous Multi-Language Software Development Lab
 * Workstream H: Multi-Language Project Scaffolding, Sandboxed Runner, and Auto-Debugging Loop
 */

const fs = require('fs');
const path = require('path');
const { spawn, exec } = require('child_process');
const { errorDiagnostics, ErrorCode } = require('../errorDiagnosticsService.js');

const PROJECTS_ROOT = path.join(__dirname, '..', '..', 'workspace', 'projects');

class AutonomousDevelopmentLab {
  constructor() {
    this._ensureDir();
  }

  _ensureDir() {
    if (!fs.existsSync(PROJECTS_ROOT)) {
      fs.mkdirSync(PROJECTS_ROOT, { recursive: true });
    }
  }

  /**
   * Scaffolds a complete project structure
   */
  async createProject(projectName, options = {}) {
    if (!projectName || !/^[a-zA-Z0-9_-]+$/.test(projectName)) {
      throw new Error('Project name must contain only letters, numbers, hyphens, and underscores.');
    }

    const lang = (options.language || 'python').toLowerCase();
    const projDir = path.join(PROJECTS_ROOT, projectName);
    if (!fs.existsSync(projDir)) {
      fs.mkdirSync(projDir, { recursive: true });
    }

    const createdFiles = [];

    if (lang === 'python') {
      const mainPy = path.join(projDir, 'main.py');
      const testPy = path.join(projDir, 'test_main.py');
      const reqTxt = path.join(projDir, 'requirements.txt');
      const readme = path.join(projDir, 'README.md');

      const mainContent = options.code || `# ${projectName} - Autonomous VISION Python Project (MADE BY LOKESH)\nimport sys\n\ndef run():\n    print(f"Executing ${projectName} under Python {sys.version.split()[0]}")\n    return 0\n\nif __name__ == '__main__':\n    sys.exit(run())\n`;
      const testContent = `# Unit tests for ${projectName}\nimport unittest\nfrom main import run\n\nclass TestMain(unittest.TestCase):\n    def test_run(self):\n        self.assertEqual(run(), 0)\n\nif __name__ == '__main__':\n    unittest.main()\n`;

      fs.writeFileSync(mainPy, mainContent, 'utf8');
      fs.writeFileSync(testPy, testContent, 'utf8');
      fs.writeFileSync(reqTxt, '# Project dependencies\n', 'utf8');
      fs.writeFileSync(readme, `# ${projectName}\n\nGenerated by VISION Autonomous Development Lab.\n`, 'utf8');

      createdFiles.push('main.py', 'test_main.py', 'requirements.txt', 'README.md');
    } else if (lang === 'javascript' || lang === 'node') {
      const indexJs = path.join(projDir, 'index.js');
      const testJs = path.join(projDir, 'test.js');
      const pkgJson = path.join(projDir, 'package.json');
      const readme = path.join(projDir, 'README.md');

      const indexContent = options.code || `// ${projectName} - Autonomous VISION Node.js Project (MADE BY LOKESH)\nfunction run() {\n  console.log('Executing ${projectName} under Node.js ' + process.version);\n  return 0;\n}\n\nif (require.main === module) {\n  run();\n}\n\nmodule.exports = { run };\n`;
      const testContent = `const assert = require('assert');\nconst { run } = require('./index.js');\nassert.strictEqual(run(), 0);\nconsole.log('Project unit tests passed.');\n`;
      const pkgContent = JSON.stringify({
        name: projectName,
        version: '1.0.0',
        description: `Project ${projectName} generated by VISION AI`,
        main: 'index.js',
        scripts: { test: 'node test.js' }
      }, null, 2);

      fs.writeFileSync(indexJs, indexContent, 'utf8');
      fs.writeFileSync(testJs, testContent, 'utf8');
      fs.writeFileSync(pkgJson, pkgContent, 'utf8');
      fs.writeFileSync(readme, `# ${projectName}\n\nGenerated by VISION Autonomous Development Lab.\n`, 'utf8');

      createdFiles.push('index.js', 'test.js', 'package.json', 'README.md');
    } else {
      throw new Error(`Language "${lang}" is not currently supported for automated scaffolding. Supported: python, javascript`);
    }

    return {
      success: true,
      projectName,
      language: lang,
      projectPath: projDir,
      files: createdFiles,
      summary: `Scaffolded ${lang} project "${projectName}" at ${projDir} with files: ${createdFiles.join(', ')}, sir.`
    };
  }

  /**
   * Executes code within project sandbox with timeout protection
   */
  async runCode(projectName, options = {}) {
    const projDir = path.join(PROJECTS_ROOT, projectName);
    if (!fs.existsSync(projDir)) {
      throw new Error(`Project "${projectName}" does not exist in workspace.`);
    }

    const lang = (options.language || 'python').toLowerCase();
    const entrypoint = options.entrypoint || (lang === 'python' ? 'main.py' : 'index.js');
    const entryPath = path.join(projDir, entrypoint);

    if (!fs.existsSync(entryPath)) {
      throw new Error(`Entrypoint "${entrypoint}" does not exist in project "${projectName}".`);
    }

    const timeoutMs = options.timeoutMs || 15000;
    const cmd = lang === 'python' ? 'python' : 'node';
    const args = [entrypoint];

    const t0 = Date.now();
    return new Promise((resolve) => {
      let stdout = '';
      let stderr = '';
      let isTimedOut = false;

      const child = spawn(cmd, args, { cwd: projDir, stdio: ['ignore', 'pipe', 'pipe'] });

      const timer = setTimeout(() => {
        isTimedOut = true;
        child.kill('SIGKILL');
      }, timeoutMs);

      child.stdout.on('data', (d) => { stdout += d.toString(); });
      child.stderr.on('data', (d) => { stderr += d.toString(); });

      child.on('close', (code) => {
        clearTimeout(timer);
        const durationMs = Date.now() - t0;

        if (isTimedOut) {
          const diag = errorDiagnostics.record(new Error(`Execution exceeded safety limit of ${timeoutMs}ms`), {
            subsystem: 'devlab',
            code: ErrorCode.ERR_DEVLAB_EXECUTION_TIMEOUT,
            projectName
          });
          return resolve({
            success: false,
            timedOut: true,
            exitCode: -1,
            stdout,
            stderr: `Process killed: execution exceeded timeout threshold of ${timeoutMs / 1000}s.`,
            durationMs,
            diagnostics: diag,
            summary: `Execution timed out after ${timeoutMs / 1000}s, sir.`
          });
        }

        const success = code === 0;
        let diag = null;
        if (!success) {
          diag = errorDiagnostics.record(new Error(stderr || `Process exited with code ${code}`), {
            subsystem: 'devlab',
            code: ErrorCode.ERR_DEVLAB_BUILD_ERROR,
            projectName,
            entrypoint
          });
        }

        resolve({
          success,
          exitCode: code,
          stdout: stdout.trim(),
          stderr: stderr.trim(),
          durationMs,
          diagnostics: diag,
          summary: success
            ? `Execution succeeded in ${durationMs}ms (Exit Code 0):\n${stdout.substring(0, 300)}`
            : `Execution failed with exit code ${code}:\n${stderr.substring(0, 300)}`
        });
      });

      child.on('error', (err) => {
        clearTimeout(timer);
        const diag = errorDiagnostics.record(err, { subsystem: 'devlab', appName: cmd });
        resolve({
          success: false,
          exitCode: -1,
          stdout: '',
          stderr: err.message,
          diagnostics: diag,
          summary: `Failed to invoke runner "${cmd}": ${err.message}`
        });
      });
    });
  }

  /**
   * Analyzes execution failure and attempts automatic self-repair
   */
  async debugAndRepair(projectName, options = {}) {
    const projDir = path.join(PROJECTS_ROOT, projectName);
    const lang = (options.language || 'python').toLowerCase();
    const entrypoint = options.entrypoint || (lang === 'python' ? 'main.py' : 'index.js');
    const entryPath = path.join(projDir, entrypoint);

    if (!fs.existsSync(entryPath)) {
      throw new Error(`File "${entrypoint}" does not exist in project "${projectName}".`);
    }

    const currentCode = fs.readFileSync(entryPath, 'utf8');
    const failureLog = options.failureLog || '';

    // If replacement code provided directly, apply it
    if (options.repairedCode) {
      fs.writeFileSync(entryPath, options.repairedCode, 'utf8');
      const verification = await this.runCode(projectName, { language: lang, entrypoint });
      return {
        success: verification.success,
        repaired: true,
        verification,
        summary: verification.success 
          ? `Self-repaired "${entrypoint}". Verification run succeeded with exit code 0, sir.`
          : `Applied repair patch to "${entrypoint}", but verification run failed: ${verification.stderr}`
      };
    }

    // Heuristic auto-repair for common syntax errors
    let repairedCode = currentCode;
    let patchDescription = '';

    if (lang === 'python') {
      if (failureLog.includes('SyntaxError') && failureLog.includes(':') && currentCode.includes('def run()')) {
        repairedCode = currentCode.replace(/def run\(\)\s*$/m, 'def run():');
        patchDescription = 'Added missing colon to function definition.';
      } else if (failureLog.includes('IndentationError')) {
        repairedCode = currentCode.replace(/\t/g, '    ');
        patchDescription = 'Replaced invalid tabs with 4 spaces.';
      }
    }

    if (repairedCode !== currentCode) {
      fs.writeFileSync(entryPath, repairedCode, 'utf8');
      const verification = await this.runCode(projectName, { language: lang, entrypoint });
      return {
        success: verification.success,
        repaired: true,
        patchDescription,
        verification,
        summary: `Auto-repair applied (${patchDescription}). Verification result: ${verification.summary}`
      };
    }

    return {
      success: false,
      repaired: false,
      summary: `Automated repair heuristics could not determine an unambiguous patch for the error. Please review the trace:\n${failureLog.substring(0, 300)}`
    };
  }
}

const autonomousDevelopmentLabInstance = new AutonomousDevelopmentLab();

module.exports = {
  AutonomousDevelopmentLab,
  autonomousDevelopmentLab: autonomousDevelopmentLabInstance,
  PROJECTS_ROOT
};
